def create_provider(
    llm_name: str,
    llm_model: str,
    env: Dict[str, str],
    logger: logging.Logger,
) -> BaseLLMProvider:
    provider_key = llm_name.lower()
    if provider_key == "gemini":
        return GeminiProvider(provider_key, llm_model, env, logger)
    if provider_key in {"sonnet", "claude"}:
        return SonnetProvider(provider_key, llm_model, env, logger)
    if provider_key == "llama":
        return LlamaProvider(provider_key, llm_model, env, logger)
    if provider_key == "qwen":
        return QwenProvider(provider_key, llm_model, env, logger)

    supported = "gemini, sonnet/claude, llama, qwen"
    raise ValueError(f"Unsupported llm provider '{llm_name}'. Supported: {supported}")
