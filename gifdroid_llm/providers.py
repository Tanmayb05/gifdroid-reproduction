@dataclass
class SuggestedAction:
    type: str  # tap | scroll | type_text | press_back | press_home | wait | done
    target_description: str = ""
    resource_id: str | None = None
    coordinates: list[int] | None = None  # [x, y]
    text: str | None = None


@dataclass
class ScreenDescription:
    current_screen: str
    visible_elements: list[str]
    suggested_action: SuggestedAction
    reasoning: str
    confidence: float


@dataclass
class ExecutableAction:
    type: str  # tap | scroll | type_text | press_back | press_home | wait | done
    resource_id: str | None = None
    coordinates: list[int] | None = None  # [x, y]
    text: str | None = None
    direction: str | None = None  # for scroll: up|down|left|right
    target_description: str = ""


@dataclass
class ActionDecision:
    continue_automation: bool
    action: ExecutableAction | None
    reasoning: str
    confidence: float


@dataclass(frozen=True)
class ProviderAction:
    screen_description: str
    action_type: str
    target: str
    details: str
    confidence: float
    timestamp_sec: float = 0.0


class ProviderError(RuntimeError):
    """Raised for provider-specific connectivity or inference failures."""


class BaseLLMProvider(ABC):
    """Common abstraction for open/closed model adapters."""

    def __init__(
        self,
        llm_name: str,
        llm_model: str,
        env: Dict[str, str],
        logger: logging.Logger,
    ) -> None:
        self.llm_name = llm_name
        self.llm_model = llm_model
        self.env = env
        self.logger = logger
        self.raw_llm_response: str | None = None

    @abstractmethod
    def infer_actions(self, keyframes: List[Keyframe]) -> List[ProviderAction]:
        """Infer action hypotheses from selected keyframes."""

    def infer_actions_from_video(self, video_path: Path) -> List[ProviderAction]:
        """Infer actions directly from a video file (video mode). Override in subclasses."""
        raise NotImplementedError(
            f"Provider '{self.llm_name}' does not support video_mode. "
            "Only 'gemini' is currently supported."
        )

    def validate_connection(self) -> None:
        """Optional provider preflight hook."""
        return None

    def _deterministic_fallback(self, keyframes: List[Keyframe], source: str) -> List[ProviderAction]:
        actions: List[ProviderAction] = []
        for idx, kf in enumerate(keyframes):
            if idx == 0:
                action_type = "launch_app"
                target = "app_entrypoint"
                details = f"{source}: initial frame likely app launch or resumed state"
                confidence = 0.88
            elif kf.motion_score >= 18:
                action_type = "tap"
                target = f"ui_element_step_{idx}"
                details = f"{source}: high visual transition suggests a click/tap action"
                confidence = 0.74
            elif kf.motion_score >= 9:
                action_type = "scroll"
                target = "scrollable_view"
                details = f"{source}: medium transition suggests scrolling/swiping"
                confidence = 0.66
            else:
                action_type = "wait"
                target = "current_screen"
                details = f"{source}: minimal transition indicates waiting or subtle input"
                confidence = 0.58

            desc = (
                f"Frame at {kf.timestamp_sec:.2f}s with motion_score={kf.motion_score:.2f}; "
                f"heuristic interpretation generated by {source}."
            )
            actions.append(
                ProviderAction(
                    screen_description=desc,
                    action_type=action_type,
                    target=target,
                    details=details,
                    confidence=confidence,
                )
            )
        return actions


class GeminiProvider(BaseLLMProvider):
    def validate_connection(self) -> None:
        self.logger.info(
            "Gemini preflight started | model=%s | validating API key and endpoint access",
            self.llm_model,
        )
        _ = self._call_gemini(
            prompt="Reply with exactly: OK",
            timeout_sec=30,
            request_kind="preflight",
        )
        self.logger.info("Gemini preflight successful | model=%s", self.llm_model)

    def infer_actions(self, keyframes: List[Keyframe]) -> List[ProviderAction]:
        if not keyframes:
            return []

        self.logger.info(
            "Sending Gemini inference request | model=%s | keyframes=%d",
            self.llm_model,
            len(keyframes),
        )
        prompt = self._build_action_prompt(keyframes)
        try:
            raw_text = self._call_gemini(
                prompt=prompt,
                timeout_sec=90,
                request_kind="action_inference",
            )
            parsed = self._parse_actions(raw_text, keyframes)
            if parsed:
                self.logger.info(
                    "Gemini inference parsed successfully | parsed_actions=%d",
                    len(parsed),
                )
                return parsed
            self.logger.warning(
                "Gemini response could not be parsed into actions; falling back to deterministic heuristic."
            )
        except ProviderError as exc:
            self.logger.warning(
                "Gemini inference request failed (%s); falling back to deterministic heuristic.",
                exc,
            )

        return self._deterministic_fallback(keyframes, source="gemini_fallback")

    def describe_screen(
        self,
        screenshot_path: Path,
        accessibility_tree_xml: str | None = None,
    ) -> ScreenDescription:
        """Send a screenshot (and optionally accessibility tree) to Gemini and return structured screen description."""
        import xml.etree.ElementTree as ET

        # Build clickable elements summary from XML (avoid dumping raw verbose XML)
        clickable_summary = ""
        if accessibility_tree_xml:
            try:
                tree = ET.fromstring(accessibility_tree_xml)
                clickable = [
                    n for n in tree.findall(".//*")
                    if n.get("clickable") == "true"
                ][:20]
                lines = []
                for el in clickable:
                    rid = el.get("resource-id", "")
                    text = el.get("text", "")
                    bounds = el.get("bounds", "")
                    lines.append(f"  resource-id={rid!r} text={text!r} bounds={bounds}")
                if lines:
                    clickable_summary = "\n\nClickable UI elements from accessibility tree:\n" + "\n".join(lines)
            except ET.ParseError:
                pass

        prompt = (
            "You are an Android UI automation assistant. "
            "Look at this screenshot of an Android screen and return ONLY a JSON object with these keys:\n"
            '  "current_screen": short description of what screen/state is shown,\n'
            '  "visible_elements": array of visible UI element descriptions,\n'
            '  "suggested_action": object with keys:\n'
            '    "type": one of tap|scroll|type_text|press_back|press_home|wait|done,\n'
            '    "target_description": natural language description of target,\n'
            '    "resource_id": resource-id string or null,\n'
            '    "coordinates": [x, y] pixel coordinates or null,\n'
            '    "text": text to type if type_text else null,\n'
            '  "reasoning": why this action is the logical next step,\n'
            '  "confidence": float 0.0-1.0\n'
            "Return ONLY valid JSON, no markdown fences."
            + clickable_summary
        )

        # Read screenshot as base64
        with screenshot_path.open("rb") as f:
            img_b64 = base64.b64encode(f.read()).decode("ascii")

        # Use Vertex AI if no API key, else Google AI Studio
        api_key = self.env.get("GOOGLE_GENERATIVE_AI_API_KEY", "").strip()
        if api_key:
            url = (
                "https://generativelanguage.googleapis.com/v1beta/models/"
                f"{self.llm_model}:generateContent?key={api_key}"
            )
            headers = {"Content-Type": "application/json"}
        else:
            token, adc_project_id = self._build_default_adc_token()
            project_id = (
                str(self.env.get("GEMINI_VERTEX_PROJECT_ID", "")).strip() or adc_project_id
            )
            if not project_id:
                raise ProviderError("No project_id for Vertex AI in describe_screen")
            location = str(self.env.get("GEMINI_VERTEX_LOCATION", "us-central1")).strip() or "us-central1"
            url = (
                f"https://{location}-aiplatform.googleapis.com/v1/"
                f"projects/{project_id}/locations/{location}/publishers/google/models/"
                f"{self.llm_model}:generateContent"
            )
            headers = {
                "Authorization": f"Bearer {token}",
                "Content-Type": "application/json",
            }

        payload = {
            "contents": [{
                "role": "user",
                "parts": [
                    {"inlineData": {"mimeType": "image/png", "data": img_b64}},
                    {"text": prompt},
                ],
            }],
            "generationConfig": {"temperature": 0.1},
        }
        payload_bytes = json.dumps(payload).encode("utf-8")
        req = url_request.Request(url=url, data=payload_bytes, headers=headers, method="POST")

        self.logger.info("describe_screen: sending screenshot to Gemini | model=%s", self.llm_model)
        start = time.perf_counter()
        try:
            with url_request.urlopen(req, timeout=90) as resp:
                response_text = resp.read().decode("utf-8")
        except url_error.HTTPError as exc:
            err_body = exc.read().decode("utf-8", errors="replace")
            raise ProviderError(f"describe_screen HTTP {exc.code}: {err_body[:300]}") from exc
        except url_error.URLError as exc:
            raise ProviderError(f"describe_screen URL error: {exc}") from exc

        elapsed = time.perf_counter() - start
        self.logger.info("describe_screen: response received | elapsed_sec=%.2f", elapsed)

        try:
            data = json.loads(response_text)
            raw_text = self._extract_text(data)
        except (json.JSONDecodeError, KeyError, TypeError, ProviderError) as exc:
            raise ProviderError(f"describe_screen: invalid response format: {exc}") from exc

        return self._parse_screen_description(raw_text)

    def _parse_screen_description(self, raw_text: str) -> ScreenDescription:
        text = raw_text.strip()
        # Strip markdown fences if present
        if "```" in text:
            for chunk in text.split("```"):
                cleaned = chunk.strip()
                if cleaned.startswith("json"):
                    cleaned = cleaned[4:].strip()
                if cleaned.startswith("{"):
                    text = cleaned
                    break
        try:
            obj = json.loads(text)
        except json.JSONDecodeError as exc:
            raise ProviderError(f"describe_screen: could not parse JSON: {exc}\nRaw: {text[:300]}") from exc

        action_raw = obj.get("suggested_action", {}) or {}
        coords = action_raw.get("coordinates")
        if coords and isinstance(coords, list) and len(coords) == 2:
            try:
                coords = [int(coords[0]), int(coords[1])]
            except (TypeError, ValueError):
                coords = None
        else:
            coords = None

        suggested = SuggestedAction(
            type=str(action_raw.get("type", "wait")).strip() or "wait",
            target_description=str(action_raw.get("target_description", "")).strip(),
            resource_id=action_raw.get("resource_id") or None,
            coordinates=coords,
            text=action_raw.get("text") or None,
        )

        confidence_raw = obj.get("confidence", 0.5)
        try:
            confidence = float(confidence_raw)
        except (TypeError, ValueError):
            confidence = 0.5

        return ScreenDescription(
            current_screen=str(obj.get("current_screen", "")).strip(),
            visible_elements=list(obj.get("visible_elements", [])),
            suggested_action=suggested,
            reasoning=str(obj.get("reasoning", "")).strip(),
            confidence=max(0.0, min(1.0, confidence)),
        )

    def decide_next_action(
        self,
        history: list,
        screenshot: "PIL.Image.Image",
        accessibility_tree: str | None,
        task_description: str = "",
    ) -> "ActionDecision":
        """Given history of turns and current screenshot, decide the next action.

        Returns an ActionDecision with continue_automation flag and action details.
        """
        import io
        import xml.etree.ElementTree as ET

        # Build clickable elements summary
        clickable_summary = ""
        if accessibility_tree:
            try:
                tree = ET.fromstring(accessibility_tree)
                clickable = [
                    n for n in tree.findall(".//*")
                    if n.get("clickable") == "true"
                ][:20]
                lines = []
                for el in clickable:
                    rid = el.get("resource-id", "")
                    text = el.get("text", "")
                    bounds = el.get("bounds", "")
                    lines.append(f"  resource-id={rid!r} text={text!r} bounds={bounds}")
                if lines:
                    clickable_summary = "\n\nClickable UI elements:\n" + "\n".join(lines)
            except ET.ParseError:
                pass

        # Build history summary
        history_text = ""
        if history:
            steps = []
            for turn in history:
                action_desc = "initial state"
                if turn.action_taken:
                    a = turn.action_taken
                    action_desc = f"{a.type}"
                    if a.resource_id:
                        action_desc += f" on {a.resource_id}"
                    elif a.coordinates:
                        action_desc += f" at {a.coordinates}"
                steps.append(f"  Step {turn.step_index + 1}: {action_desc}")
            history_text = "\n\nPrevious steps taken:\n" + "\n".join(steps)

        task_line = f"\nTask: {task_description}" if task_description else ""

        prompt = (
            "You are an Android UI automation assistant driving a live device.{task_line}\n"
            "Look at the current screenshot and decide the next action.\n"
            "Return ONLY a JSON object with these keys:\n"
            '  "continue": true if more actions are needed, false if task is complete,\n'
            '  "action": object with keys:\n'
            '    "type": one of tap|scroll|type_text|press_back|press_home|wait|done,\n'
            '    "resource_id": resource-id string or null,\n'
            '    "coordinates": [x, y] pixel coordinates or null,\n'
            '    "text": text string for type_text else null,\n'
            '    "direction": up|down|left|right for scroll else null,\n'
            '    "target_description": natural language description of target,\n'
            '  "reasoning": why this is the right next action,\n'
            '  "confidence": float 0.0-1.0\n'
            "If continue=false, action can be null.\n"
            "Return ONLY valid JSON, no markdown fences."
        ).format(task_line=task_line) + history_text + clickable_summary

        # Encode current screenshot as base64 PNG
        buf = io.BytesIO()
        screenshot.save(buf, format="PNG")
        img_b64 = base64.b64encode(buf.getvalue()).decode("ascii")

        api_key = self.env.get("GOOGLE_GENERATIVE_AI_API_KEY", "").strip()
        if api_key:
            url = (
                "https://generativelanguage.googleapis.com/v1beta/models/"
                f"{self.llm_model}:generateContent?key={api_key}"
            )
            headers = {"Content-Type": "application/json"}
        else:
            token, adc_project_id = self._build_default_adc_token()
            project_id = (
                str(self.env.get("GEMINI_VERTEX_PROJECT_ID", "")).strip() or adc_project_id
            )
            if not project_id:
                raise ProviderError("No project_id for Vertex AI in decide_next_action")
            location = str(self.env.get("GEMINI_VERTEX_LOCATION", "us-central1")).strip() or "us-central1"
            url = (
                f"https://{location}-aiplatform.googleapis.com/v1/"
                f"projects/{project_id}/locations/{location}/publishers/google/models/"
                f"{self.llm_model}:generateContent"
            )
            headers = {
                "Authorization": f"Bearer {token}",
                "Content-Type": "application/json",
            }

        payload = {
            "contents": [{
                "role": "user",
                "parts": [
                    {"inlineData": {"mimeType": "image/png", "data": img_b64}},
                    {"text": prompt},
                ],
            }],
            "generationConfig": {"temperature": 0.1},
        }
        payload_bytes = json.dumps(payload).encode("utf-8")
        req = url_request.Request(url=url, data=payload_bytes, headers=headers, method="POST")

        self.logger.info("decide_next_action: calling Gemini | model=%s", self.llm_model)
        start = time.perf_counter()
        try:
            with url_request.urlopen(req, timeout=90) as resp:
                response_text = resp.read().decode("utf-8")
        except url_error.HTTPError as exc:
            err_body = exc.read().decode("utf-8", errors="replace")
            raise ProviderError(f"decide_next_action HTTP {exc.code}: {err_body[:300]}") from exc
        except url_error.URLError as exc:
            raise ProviderError(f"decide_next_action URL error: {exc}") from exc

        elapsed = time.perf_counter() - start
        self.logger.info("decide_next_action: response received | elapsed_sec=%.2f", elapsed)

        data = json.loads(response_text)
        raw_text = self._extract_text(data)
        return self._parse_action_decision(raw_text)

    def _parse_action_decision(self, raw_text: str) -> "ActionDecision":
        text = raw_text.strip()
        if "```" in text:
            for chunk in text.split("```"):
                cleaned = chunk.strip()
                if cleaned.startswith("json"):
                    cleaned = cleaned[4:].strip()
                if cleaned.startswith("{"):
                    text = cleaned
                    break
        try:
            obj = json.loads(text)
        except json.JSONDecodeError as exc:
            raise ProviderError(f"decide_next_action: could not parse JSON: {exc}\nRaw: {text[:300]}") from exc

        continue_auto = bool(obj.get("continue", True))
        reasoning = str(obj.get("reasoning", "")).strip()
        confidence_raw = obj.get("confidence", 0.5)
        try:
            confidence = float(confidence_raw)
        except (TypeError, ValueError):
            confidence = 0.5

        action_raw = obj.get("action") or {}
        if not action_raw or not continue_auto:
            action = None
        else:
            coords = action_raw.get("coordinates")
            if coords and isinstance(coords, list) and len(coords) == 2:
                try:
                    coords = [int(coords[0]), int(coords[1])]
                except (TypeError, ValueError):
                    coords = None
            else:
                coords = None
            action = ExecutableAction(
                type=str(action_raw.get("type", "wait")).strip() or "wait",
                resource_id=action_raw.get("resource_id") or None,
                coordinates=coords,
                text=action_raw.get("text") or None,
                direction=action_raw.get("direction") or None,
                target_description=str(action_raw.get("target_description", "")).strip(),
            )

        return ActionDecision(
            continue_automation=continue_auto,
            action=action,
            reasoning=reasoning,
            confidence=max(0.0, min(1.0, confidence)),
        )

    def _build_action_prompt(self, keyframes: List[Keyframe]) -> str:
        keyframe_lines = [
            (
                f"- idx={idx + 1}, timestamp_sec={frame.timestamp_sec:.3f}, "
                f"motion_score={frame.motion_score:.3f}"
            )
            for idx, frame in enumerate(keyframes)
        ]
        joined = "\n".join(keyframe_lines)
        return (
            "You are inferring a mobile bug reproduction trace from frame metadata.\n"
            "Return ONLY valid JSON as an array, one object per keyframe, with keys:\n"
            "screen_description, action_type, target, details, confidence.\n"
            "confidence must be between 0 and 1.\n"
            "Keyframes:\n"
            f"{joined}\n"
        )

    def _call_gemini(self, prompt: str, timeout_sec: int, request_kind: str) -> str:
        api_key = self.env.get("GOOGLE_GENERATIVE_AI_API_KEY", "").strip()

        headers = {"Content-Type": "application/json"}
        endpoint_name = ""

        if api_key:
            auth_mode = "api_key"
            endpoint_name = "google_ai_studio"
            url = (
                "https://generativelanguage.googleapis.com/v1beta/models/"
                f"{self.llm_model}:generateContent?key={api_key}"
            )
        else:
            auth_mode = "adc_default"
            token, adc_project_id = self._build_default_adc_token()
            vertex_project_id = (
                str(self.env.get("GEMINI_VERTEX_PROJECT_ID", "")).strip() or adc_project_id
            )
            if not vertex_project_id:
                raise ProviderError(
                    "ADC did not provide a project_id and GEMINI_VERTEX_PROJECT_ID is not set."
                )
            headers["Authorization"] = f"Bearer {token}"
            location = str(self.env.get("GEMINI_VERTEX_LOCATION", "us-central1")).strip() or "us-central1"
            endpoint_name = "vertex_ai"
            url = (
                f"https://{location}-aiplatform.googleapis.com/v1/"
                f"projects/{vertex_project_id}/locations/{location}/publishers/google/models/"
                f"{self.llm_model}:generateContent"
            )
            self.logger.info(
                "Gemini ADC default credentials loaded | adc_project=%s | runtime_project=%s | token_present=%s",
                adc_project_id,
                vertex_project_id,
                bool(token),
            )
        self.logger.info(
            "Gemini auth route selected | route=%s | endpoint=%s",
            auth_mode,
            endpoint_name,
        )

        payload = {
            "contents": [{"role": "user", "parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.1},
        }
        payload_bytes = json.dumps(payload).encode("utf-8")
        req = url_request.Request(
            url=url,
            data=payload_bytes,
            headers=headers,
            method="POST",
        )

        self.logger.info(
            "Gemini API request sent | kind=%s | model=%s | auth=%s | endpoint=%s | waiting for response",
            request_kind,
            self.llm_model,
            auth_mode,
            endpoint_name,
        )
        start = time.perf_counter()
        try:
            with url_request.urlopen(req, timeout=timeout_sec) as response:
                response_text = response.read().decode("utf-8")
        except url_error.HTTPError as exc:
            err_body = exc.read().decode("utf-8", errors="replace")
            raise ProviderError(
                f"Gemini HTTP error {exc.code} during {request_kind}: {err_body[:300]}"
            ) from exc
        except url_error.URLError as exc:
            raise ProviderError(f"Gemini URL error during {request_kind}: {exc}") from exc
        except TimeoutError as exc:
            raise ProviderError(
                f"Gemini request timed out during {request_kind} after {timeout_sec}s"
            ) from exc

        elapsed = time.perf_counter() - start
        self.logger.info(
            "Gemini API response received | kind=%s | elapsed_sec=%.2f",
            request_kind,
            elapsed,
        )

        try:
            data = json.loads(response_text)
            return self._extract_text(data)
        except (json.JSONDecodeError, KeyError, TypeError) as exc:
            raise ProviderError(f"Invalid Gemini response format during {request_kind}") from exc

    def _build_default_adc_token(self) -> tuple[str, str | None]:
        try:
            import google.auth
            from google.auth.transport.requests import Request
        except ImportError as exc:
            raise ProviderError(
                "google-auth is required for ADC auth. "
                "Install dependencies from gifdroid_llm/requirements.txt"
            ) from exc

        try:
            creds, project_id = google.auth.default(
                scopes=["https://www.googleapis.com/auth/cloud-platform"]
            )
            creds.refresh(Request())
        except Exception as exc:
            raise ProviderError(
                "Failed to load Application Default Credentials via google.auth.default(). "
                "Set GOOGLE_APPLICATION_CREDENTIALS, run gcloud auth application-default login, "
                "or provide GOOGLE_GENERATIVE_AI_API_KEY."
            ) from exc

        token = getattr(creds, "token", None)
        if not token:
            raise ProviderError("ADC token refresh returned empty token")
        return token, project_id

    def _extract_text(self, response_data: Dict[str, object]) -> str:
        candidates = response_data.get("candidates")
        if not isinstance(candidates, list) or not candidates:
            raise ProviderError("Gemini response missing candidates")

        first = candidates[0]
        if not isinstance(first, dict):
            raise ProviderError("Gemini candidate payload has invalid structure")

        content = first.get("content")
        if not isinstance(content, dict):
            raise ProviderError("Gemini candidate missing content")

        parts = content.get("parts")
        if not isinstance(parts, list) or not parts:
            raise ProviderError("Gemini candidate missing parts")

        texts: List[str] = []
        for part in parts:
            if isinstance(part, dict):
                text = part.get("text")
                if isinstance(text, str) and text.strip():
                    texts.append(text.strip())

        if not texts:
            raise ProviderError("Gemini response contained no text parts")
        return "\n".join(texts)

    def _parse_actions(
        self,
        raw_text: str,
        keyframes: List[Keyframe],
    ) -> List[ProviderAction] | None:
        text = raw_text.strip()
        if "```" in text:
            chunks = text.split("```")
            for chunk in chunks:
                cleaned = chunk.strip()
                if cleaned.startswith("json"):
                    cleaned = cleaned[4:].strip()
                if cleaned.startswith("["):
                    text = cleaned
                    break
        if not text.startswith("["):
            return None

        try:
            parsed = json.loads(text)
        except json.JSONDecodeError:
            return None
        if not isinstance(parsed, list):
            return None

